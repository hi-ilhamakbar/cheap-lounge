/** Resolve "errors.emailInvalid"-style keys; falls back to errors.generic. */
export function translateKey(dict: Dict, key: string): string {
  const parts = key.split(".");
  let cur: unknown = dict;
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in (cur as Record<string, unknown>)) cur = (cur as Record<string, unknown>)[p];
    else return dict.errors.generic;
  }
  return typeof cur === "string" ? cur : dict.errors.generic;
}

export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
